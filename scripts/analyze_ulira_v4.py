"""
scripts/analyze_ulira_v4.py
===========================
Cross-dataset analysis of the Hayes-faithful U-LiRA v4 (ledger D4/E30; fields written by
`run_ulira.py --v4`): extends the dSprites pilot (E30, n=21) to dSprites + CelebA + MPI3D.

  U1 coverage         rows with all 3 shadows per dataset
  U2 zero cluster     share of scored models with v3 leak < 0.01 vs v4 advantage < 0.05  (the E29 symptom)
  U3 range            v4 advantage by method (min = closest any method gets to 'indistinguishable from retraining')
  U4 agreement        Spearman(v4 adv, TOFU KS) and with attack@r / relearn criteria, pooled & per dataset;
                      v3 on the SAME rows for comparison
  U5 claim check      E18/E21: "TOFU / U-LiRA cluster with geometry and are decoupled from the generative attack".
                      rho(v4, attack@r) and rho(v3, attack@r), pooled (ranks within dataset) and method-controlled.
Writes results/analysis_oct2026/ulira_v4{tag}.{json,md}.   Root: env CU_ROOT.
Options: --fams b1[,b4]  model families to include (default b1 = the 126 beta=1 models, which reproduces the
                         pre-existing ulira_v4.{json,md}); --tag SUFFIX  output-name suffix (default "").
"""
from __future__ import annotations
import argparse, json, math, os, sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy.stats import rankdata

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analyze_criterion_alternatives as C  # noqa: E402

ROOT, OUT = C.ROOT, C.OUT
DATASETS = C.DATASETS
B = 1000


def load(fams=("b1",)):
    cache = {}
    cc, _ = C.load()                                  # rows with relearn criteria (beta=1 and 4)
    for (ds, fam), rows in cc.items():
        if fam in fams:
            cache[(ds, fam)] = {r["run"]: r for r in rows}
    out = []
    for fam, suffix in C.FAMS:
        if fam not in fams:
            continue
        for ds in DATASETS:
            p = ROOT / "results" / (ds + suffix) / "dense_recovery.json"
            rows = json.loads(p.read_text())
            for r in rows:
                if r["method"] in ("baseline", "oracle") or r.get("ulira_adv") is None:
                    continue
                d = dict(_ds=ds, _fam=fam, _m=C.canon(r["method"]), run=r["run"], v4=r["ulira_adv"], v4raw=r.get("ulira_adv_raw"),
                         post_in=r.get("ulira_post_in"), v3=r.get("ulira_leak"), tofu=r.get("tofu_ks"), attack_r=r.get("attack_at_r"),
                         sat=r.get("ulira_sat"), val=r.get("val"))
                x = cache.get((ds, fam), {}).get(r["run"])
                for k in ("relearnA", "relearnF", "forget_depth", "attack_auc"):
                    d[k] = x.get(k) if x else None
                out.append(d)
    return out


def main(fams=("b1",), tag=""):
    rows = load(fams)
    OUT.mkdir(parents=True, exist_ok=True)
    L = ["# U-LiRA v4 across datasets (generated by scripts/analyze_ulira_v4.py)\n"]
    R = {}
    if not rows:
        L.append("No v4-scored rows found (run `run_ulira.py --v4 --dataset all` first).")
        (OUT / f"ulira_v4{tag}.md").write_text("\n".join(L) + "\n"); print("\n".join(L)); return
    by = defaultdict(list)
    for r in rows:
        by[r["_ds"] if len(fams) == 1 else f'{r["_ds"]} ({r["_fam"]})'].append(r)
    L += ["## U1 - coverage (models with all 3 shadow unlearnings)\n", "| dataset | scored | methods |", "|---|---|---|"]
    for ds, rr in by.items():
        L.append(f"| {ds} | {len(rr)} | {', '.join(sorted({r['_m'] for r in rr}))} |")
    R["U1"] = {ds: len(rr) for ds, rr in by.items()}

    L += ["\n## U2 - the zero cluster (E29 symptom): v3 leak < 0.01 vs v4 advantage < 0.05\n", "| dataset | n | v3 < 0.01 | v4 adv < 0.05 | v4 adv < 0.25 |", "|---|---|---|---|---|"]
    for ds, rr in list(by.items()) + [("ALL", rows)]:
        v3 = [r["v3"] for r in rr if r["v3"] is not None]; v4 = [r["v4"] for r in rr]
        L.append(f"| {ds} | {len(rr)} | {sum(x < .01 for x in v3)}/{len(v3)} | {sum(x < .05 for x in v4)}/{len(v4)} | {sum(x < .25 for x in v4)}/{len(v4)} |")

    L += ["\n## U3 - v4 advantage by method (0 = indistinguishable from retraining, 1 = fully distinguishable)\n",
          "| dataset | method | n | min | median | max |", "|---|---|---|---|---|---|"]
    for ds, rr in by.items():
        for m in sorted({r["_m"] for r in rr}):
            v = [r["v4"] for r in rr if r["_m"] == m]
            L.append(f"| {ds} | {m} | {len(v)} | {min(v):.2f} | {np.median(v):.2f} | {max(v):.2f} |")

    def rho_pooled(rs, a, b):
        return C.pooled(rs, a, b)

    def rho_within(rs, a, b):
        return C.within(rs, a, b, min_n=4)

    L += ["\n## U4/U5 - agreement and the E18/E21 claim (rows with v4; pooled = ranks within dataset; 95% CI over rows)\n",
          "| pair | n | pooled | method-controlled |", "|---|---|---|---|"]
    pairs = [("v4", "tofu"), ("v3", "tofu"), ("v4", "v3"), ("v4", "attack_r"), ("v3", "attack_r"), ("tofu", "attack_r"),
             ("v4", "attack_auc"), ("v4", "relearnA"), ("v4", "relearnF"), ("v3", "relearnA"), ("v4", "forget_depth")]
    for a, b in pairs:
        rs = [r for r in rows if C.ok(r, a, b)]
        if len(rs) < 20:
            continue
        e1 = C.boot(rs, lambda z: rho_pooled(z, a, b), B=B); e2 = C.boot(rs, lambda z: rho_within(z, a, b), B=B)
        R[f"U4|{a}|{b}"] = dict(pooled=e1, within=e2)
        L.append(f"| {a} vs {b} | {len(rs)} | {C.fm(e1)} | {C.fm(e2)} |")
    L += ["\n### per dataset (Spearman, rows within the dataset)\n", "| dataset | n | v4~tofu | v4~attack@r | v3~attack@r | tofu~attack@r | v4~relearnA |", "|---|---|---|---|---|---|---|"]
    for ds, rr in by.items():
        def sp(a, b):
            z = [r for r in rr if C.ok(r, a, b)]
            return "n/a" if len(z) < 5 else f"{C.pearson(rankdata([r[a] for r in z]), rankdata([r[b] for r in z])):+.2f}"
        L.append(f"| {ds} | {len(rr)} | {sp('v4','tofu')} | {sp('v4','attack_r')} | {sp('v3','attack_r')} | {sp('tofu','attack_r')} | {sp('v4','relearnA')} |")
    (OUT / f"ulira_v4{tag}.json").write_text(json.dumps(R, indent=1, default=float))
    (OUT / f"ulira_v4{tag}.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--fams", default="b1")
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    main(tuple(a.fams.split(",")), a.tag)
