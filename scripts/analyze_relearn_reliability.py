"""
scripts/analyze_relearn_reliability.py
======================================
How reliable is the weight-space relearning criterion?  Before reading anything into its weak link to
attack@r, check that it is not noise from one draw of k=64 attacker examples.

  T1 test-retest      Spearman between attacker seeds (0,1,2), per criterion (A, R, X, F), pooled over cells
                      (ranks within (dataset, beta) cell), with a row-bootstrap CI.
  T2 stability        rho(criterion, attack@r) separately per seed  -> is the (weak) link stable?
  T3 budget           seed-0 criterion at k=64 vs k=256 (agreement), and rho with attack@r at k=256.

Reads results/<ds>[_b4]/relearn_attack[_k<k>_lr<lr>_s<seed>].json (written by scripts/run_relearn_attack.py).
Writes results/analysis_oct2026/relearn_reliability.{json,md}.
"""
from __future__ import annotations
import json, math, sys
from pathlib import Path

import numpy as np
from scipy.stats import rankdata

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analyze_criterion_alternatives as C  # noqa: E402

ROOT, OUT = C.ROOT, C.OUT
CRIT = ["relearnA", "relearnR", "relearnX", "relearnF"]


def fname(k, seed):
    return "relearn_attack.json" if (k == 64 and seed == 0) else f"relearn_attack_k{k}_lr0.0001_s{seed}.json"


def load_variant(k, seed):
    """-> {(ds,fam): {(method,run): {crit: value}}, refs...} using the SAME definitions as the criterion script."""
    out = {}
    for ds in C.DATASETS:
        for fam, suf in C.FAMS:
            pr = ROOT / "results" / f"{ds}{suf}" / fname(k, seed)
            pj = ROOT / "results" / f"{ds}{suf}" / "dense_recovery.json"
            if not (pr.exists() and pj.exists()):
                continue
            rl = json.loads(pr.read_text())
            rmap = {(r["method"], r["run"]): r for r in rl["rows"]}
            rb, ro = rmap.get(("baseline", "baseline")), rmap.get(("oracle", "oracle"))
            if rb is None or ro is None:
                continue
            steps = rl["meta"]["eval_at"]
            rows = {}
            for key, rrow in rmap.items():
                if key[0] in ("baseline", "oracle"):
                    continue
                A, Rr, X, depth, F = C.relearn_scores(rrow, (rb, ro), steps)
                rows[key] = dict(relearnA=A, relearnR=Rr, relearnX=X, relearnF=F)
            out[(ds, fam)] = rows
    return out


def attack_map():
    m = {}
    for ds in C.DATASETS:
        for fam, suf in C.FAMS:
            pj = ROOT / "results" / f"{ds}{suf}" / "dense_recovery.json"
            if pj.exists():
                m[(ds, fam)] = {(r["method"], r["run"]): r.get("attack_at_r") for r in json.loads(pj.read_text())}
    return m


def pair_rows(v1, v2, crit):
    """aligned (cell, x, y) lists for rows present & finite in both variants."""
    cells = {}
    for cell in v1:
        if cell not in v2:
            continue
        xs, ys = [], []
        for key, a in v1[cell].items():
            b = v2[cell].get(key)
            if b is None or a.get(crit) is None or b.get(crit) is None:
                continue
            if not (math.isfinite(a[crit]) and math.isfinite(b[crit])):
                continue
            xs.append(a[crit]); ys.append(b[crit])
        if len(xs) >= 5:
            cells[cell] = (np.array(xs), np.array(ys))
    return cells


def pooled_rho(cells):
    xs, ys = [], []
    for x, y in cells.values():
        n = len(x)
        xs += list(rankdata(x) / n); ys += list(rankdata(y) / n)
    return C.pearson(xs, ys) if len(xs) > 4 else float("nan")


def boot_rho(cells, B=1000, seed=0):
    rng = np.random.default_rng(seed)
    est = pooled_rho(cells); v = []
    for _ in range(B):
        rs = {}
        for c, (x, y) in cells.items():
            i = rng.integers(0, len(x), len(x)); rs[c] = (x[i], y[i])
        t = pooled_rho(rs)
        if math.isfinite(t):
            v.append(t)
    lo, hi = np.percentile(v, [2.5, 97.5]) if len(v) > 50 else (float("nan"),) * 2
    return est, float(lo), float(hi), sum(len(x) for x, _ in cells.values())


def fm(t):
    est, lo, hi, n = t
    return "n/a" if not math.isfinite(est) else f"{est:+.2f} [{lo:+.2f},{hi:+.2f}] n={n}"


def main():
    atk = attack_map()
    V = {("s0", 64): load_variant(64, 0), ("s1", 64): load_variant(64, 1), ("s2", 64): load_variant(64, 2),
         ("s0", 256): load_variant(256, 0)}
    avail = {k: sum(len(v) for v in d.values()) for k, d in V.items()}
    L = ["# Reliability of the relearning criterion (generated by scripts/analyze_relearn_reliability.py)\n",
         "Rows available per variant: " + ", ".join(f"{k[0]}/k={k[1]}: {n}" for k, n in avail.items()) + "\n",
         "## T1 - test-retest across attacker seeds (Spearman, ranks within cell)\n",
         "| criterion | seed0 vs seed1 | seed0 vs seed2 | seed1 vs seed2 |", "|---|---|---|---|"]
    R = {"avail": {f"{k[0]}/{k[1]}": n for k, n in avail.items()}}
    for c in CRIT:
        row = []
        for a, b in ((("s0", 64), ("s1", 64)), (("s0", 64), ("s2", 64)), (("s1", 64), ("s2", 64))):
            cells = pair_rows(V[a], V[b], c) if avail[a] and avail[b] else {}
            t = boot_rho(cells) if cells else (float("nan"),) * 4
            R[f"T1|{c}|{a[0]}-{b[0]}"] = t; row.append(fm(t))
        L.append(f"| {c} | " + " | ".join(row) + " |")

    L += ["\n## T2 - rho(criterion, attack@r) per seed (pooled, ranks within cell)\n",
          "| criterion | seed 0 | seed 1 | seed 2 |", "|---|---|---|---|"]
    for c in CRIT:
        row = []
        for tag in (("s0", 64), ("s1", 64), ("s2", 64)):
            cells = {}
            for cell, rows in V[tag].items():
                xs = [(r[c], atk[cell].get(k)) for k, r in rows.items() if r.get(c) is not None and atk[cell].get(k) is not None]
                xs = [(a, b) for a, b in xs if math.isfinite(a) and math.isfinite(b)]
                if len(xs) >= 5:
                    cells[cell] = (np.array([a for a, _ in xs]), np.array([b for _, b in xs]))
            t = boot_rho(cells) if cells else (float("nan"),) * 4
            R[f"T2|{c}|{tag[0]}"] = t; row.append(fm(t))
        L.append(f"| {c} | " + " | ".join(row) + " |")

    L += ["\n## T3 - attacker budget: seed-0 k=64 vs k=256\n", "| criterion | agreement k64 vs k256 | rho(criterion@k256, attack@r) |", "|---|---|---|"]
    for c in CRIT:
        cells = pair_rows(V[("s0", 64)], V[("s0", 256)], c) if avail[("s0", 256)] else {}
        t = boot_rho(cells) if cells else (float("nan"),) * 4
        cells2 = {}
        for cell, rows in V[("s0", 256)].items():
            xs = [(r[c], atk[cell].get(k)) for k, r in rows.items() if r.get(c) is not None and atk[cell].get(k) is not None]
            xs = [(a, b) for a, b in xs if math.isfinite(a) and math.isfinite(b)]
            if len(xs) >= 5:
                cells2[cell] = (np.array([a for a, _ in xs]), np.array([b for _, b in xs]))
        t2 = boot_rho(cells2) if cells2 else (float("nan"),) * 4
        R[f"T3|{c}|agree"] = t; R[f"T3|{c}|vs_attack"] = t2
        L.append(f"| {c} | {fm(t)} | {fm(t2)} |")
    (OUT / "relearn_reliability.json").write_text(json.dumps(R, indent=1, default=float))
    (OUT / "relearn_reliability.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
